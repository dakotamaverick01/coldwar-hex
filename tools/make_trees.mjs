// Builds data/trees.bin + data/trees.json: a few detailed tree shapes made with EZ-Tree (MIT, tools/ez-tree),
// slimmed down for phones, scaled to the game's tree sizes, with soft "crown" normals on the leaf cards.
// Run from the repo root:  (cd tools && npm install three@0.186.1 --no-save --no-package-lock) ; node tools/make_trees.mjs
import fs from 'fs';
import * as THREE from 'three';
import { Tree } from './ez-tree/tree.js';
import { TreePreset } from './ez-tree/presets/index.js';

const VARIANTS = [
  // kind, preset, seed, target height (game units, matches the simple trees), leaf card size multiplier, leaf count multiplier
  { kind: 'spruce', preset: 'Pine Medium', seed: 101, h: 1.2,  leafSize: 2.6, leafCount: 0.3, children: 0.45 },
  { kind: 'spruce', preset: 'Pine Large',  seed: 202, h: 1.2,  leafSize: 2.3, leafCount: 0.35, children: 0.45 },
  { kind: 'spruce', preset: 'Pine Small',  seed: 303, h: 1.2,  leafSize: 2.7, leafCount: 0.3, children: 0.45 },
  { kind: 'broad',  preset: 'Oak Medium',  seed: 404, h: 1.0, leafSize: 2.6, leafCount: 0.7 },
  { kind: 'broad',  preset: 'Ash Medium',  seed: 505, h: 1.0, leafSize: 2.5, leafCount: 0.7 },
  { kind: 'broad',  preset: 'Aspen Medium',seed: 606, h: 1.0, leafSize: 2.3, leafCount: 1.0 },
];

const out = { note: 'Generated by tools/make_trees.mjs with EZ-Tree (MIT). Arrays are little-endian in trees.bin.', variants: [] };
const chunks = []; let offset = 0;
const push = (typed) => { const buf = Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength); const o = offset; chunks.push(buf); offset += buf.length; const pad = (4 - (offset % 4)) % 4; if (pad) { chunks.push(Buffer.alloc(pad)); offset += pad; } return [o, typed.length]; };

for (const v of VARIANTS) {
  const t = new Tree();
  t.loadPreset(v.preset);
  const o = t.options;
  o.seed = v.seed;
  // slim the shape for phones: fewer rings and sides per branch, bigger and fewer leaf cards
  for (const k of Object.keys(o.branch.sections)) o.branch.sections[k] = Math.max(2, Math.round(o.branch.sections[k] * 0.45));
  const segs = { 0: 6, 1: 4, 2: 3, 3: 3 };
  for (const k of Object.keys(o.branch.segments)) o.branch.segments[k] = Math.min(o.branch.segments[k], segs[k]);
  if (o.branch.levels > 2) o.branch.levels = 2;
  if (v.children) o.branch.children[0] = Math.round(o.branch.children[0] * v.children);
  if (v.kind === 'spruce') o.branch.segments[1] = 3;
  o.leaves.size *= v.leafSize;
  o.leaves.count = Math.max(2, Math.round(o.leaves.count * v.leafCount));
  t.generate();
  const bg = t.branchesMesh.geometry, lg = t.leavesMesh.geometry;
  bg.computeBoundingBox(); lg.computeBoundingBox();
  const top = Math.max(bg.boundingBox.max.y, lg.boundingBox.max.y);
  const s = v.h / top;
  const scaleArr = (a) => { const r = new Float32Array(a.length); for (let i = 0; i < a.length; i++) r[i] = a[i] * s; return r; };
  // leaf cards: normals point out from the crown centre (soft, round lighting), blended with the card normal
  const lp = lg.attributes.position.array, ln = lg.attributes.normal.array;
  const c = new THREE.Vector3(); lg.boundingBox.getCenter(c);
  const nn = new Float32Array(ln.length), p = new THREE.Vector3(), n = new THREE.Vector3(), q = new THREE.Vector3();
  for (let i = 0; i < lp.length; i += 3) {
    p.set(lp[i], lp[i + 1], lp[i + 2]).sub(c); p.y *= 0.7; p.y += (lg.boundingBox.max.y - lg.boundingBox.min.y) * 0.12;
    n.copy(p).normalize(); q.set(ln[i], ln[i + 1], ln[i + 2]);
    n.multiplyScalar(0.8).addScaledVector(q, 0.2).normalize();
    nn[i] = n.x; nn[i + 1] = n.y; nn[i + 2] = n.z;
  }
  // bark: a darkness value per vertex, darker near the ground (simple baked occlusion)
  const bp = bg.attributes.position.array, shade = new Float32Array(bp.length / 3);
  for (let i = 0; i < shade.length; i++) shade[i] = 0.55 + 0.45 * Math.min(1, (bp[i * 3 + 1] / top) * 2.5);
  const rec = { kind: v.kind, name: v.preset, height: v.h,
    bark: { pos: push(scaleArr(bg.attributes.position.array)), nor: push(new Float32Array(bg.attributes.normal.array)), uv: push(new Float32Array(bg.attributes.uv.array)), shade: push(shade), idx: push(new Uint16Array(bg.index.array)) },
    leaves: { pos: push(scaleArr(lp)), nor: push(nn), uv: push(new Float32Array(lg.attributes.uv.array)), idx: push(new Uint16Array(lg.index.array)) },
    tris: (bg.index.count + lg.index.count) / 3 };
  if (bg.attributes.position.count > 65535 || lg.attributes.position.count > 65535) throw new Error('too many vertices for 16-bit indices');
  out.variants.push(rec);
  console.log(v.preset.padEnd(13), 'bark tris', bg.index.count / 3, 'leaf cards', lg.index.count / 6, 'total tris', rec.tris);
}
fs.writeFileSync('data/trees.bin', Buffer.concat(chunks));
fs.writeFileSync('data/trees.json', JSON.stringify(out));
console.log('trees.bin', (offset / 1024).toFixed(0), 'KB');
